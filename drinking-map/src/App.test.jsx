import { describe, expect, it, vi } from 'vitest'
import { render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from './App.jsx'
import { STORAGE_KEY, loadStores, saveStores } from './stores.js'

describe('飲み会MAP', () => {
  it('初期店舗を日付順の一覧と地図に表示する', () => {
    render(<App />)
    const rows = within(screen.getByRole('table')).getAllByRole('row')
    expect(rows).toHaveLength(5)
    expect(rows[1]).toHaveTextContent('銀座ライオン 七丁目店')
    expect(screen.getByRole('columnheader', { name: '訪問数' })).toBeInTheDocument()
    expect(within(rows[1]).getByRole('cell', { name: '1 回' })).toBeInTheDocument()
    expect(screen.getByRole('columnheader', { name: '最終更新日' })).toBeInTheDocument()
    expect(screen.getByRole('columnheader', { name: '更新者' })).toBeInTheDocument()
    expect(screen.getByText('最終更新日が新しい順')).toBeInTheDocument()
    expect(within(rows.at(-1)).getByRole('button', { name: '店舗を追加' })).toBeInTheDocument()
    expect(within(screen.getByRole('banner')).queryByRole('button', { name: '店舗を追加' })).not.toBeInTheDocument()
    expect(document.querySelectorAll('.store-marker')).toHaveLength(3)
  })
  it('必須項目が空の場合は登録しない', async () => {
    const user = userEvent.setup()
    const fetchMock = vi.fn()
    vi.stubGlobal('fetch', fetchMock)
    render(<App />)
    await user.click(screen.getByRole('button', { name: '店舗を追加' }))
    await user.click(screen.getByRole('button', { name: '検索', exact: true }))
    expect(fetchMock).not.toHaveBeenCalled()
    expect(screen.getByRole('dialog')).toBeVisible()
    expect(localStorage.getItem(STORAGE_KEY)).toBeNull()
  })
  it('所在地を選んで登録すると一覧・ピン・保存データに追加する', async () => {
    const user = userEvent.setup()
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue({ ok: true, json: async () => [
      { place_id: 10, display_name: 'テスト居酒屋, 東京都', lat: '35.68', lon: '139.76' },
    ] }))
    render(<App />)
    await user.click(screen.getByRole('button', { name: '店舗を追加' }))
    await user.type(screen.getByLabelText(/店舗名/), 'テスト居酒屋')
    await user.clear(screen.getByLabelText(/最終更新日/))
    await user.type(screen.getByLabelText(/最終更新日/), '2026-10-13')
    await user.type(screen.getByLabelText(/更新者/), '渡邉')
    await user.click(screen.getByRole('button', { name: '検索', exact: true }))
    expect(await screen.findByRole('button', { name: '登録', exact: true })).toBeDisabled()
    await user.click(await screen.findByRole('radio'))
    await user.click(screen.getByRole('button', { name: '登録', exact: true }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByRole('link', { name: 'テスト居酒屋', exact: true })).toBeInTheDocument()
    expect(document.querySelectorAll('.store-marker')).toHaveLength(4)
    expect(loadStores().stores.find((store) => store.storeName === 'テスト居酒屋')).toMatchObject({
      updatedDate: '2026-10-13', updatedBy: '渡邉', latitude: 35.68, longitude: 139.76,
    })
  })
  it('削除をキャンセルでき、確認後だけ一覧とピンから削除する', async () => {
    const user = userEvent.setup()
    const { unmount } = render(<App />)
    await user.click(screen.getByRole('button', { name: '銀座ライオン 七丁目店を削除' }))
    await user.click(screen.getByRole('button', { name: 'キャンセル' }))
    expect(document.querySelectorAll('.store-marker')).toHaveLength(3)
    await user.click(screen.getByRole('button', { name: '銀座ライオン 七丁目店を削除' }))
    await user.click(screen.getByRole('button', { name: '削除', exact: true }))
    expect(document.querySelectorAll('.store-marker')).toHaveLength(2)
    expect(loadStores().stores).toHaveLength(2)
    unmount()
    render(<App />)
    expect(screen.queryByRole('link', { name: '銀座ライオン 七丁目店', exact: true })).not.toBeInTheDocument()
    expect(document.querySelectorAll('.store-marker')).toHaveLength(2)
  })
  it.each([
    ['通信失敗', () => Promise.reject(new Error('offline')), '位置情報を取得できませんでした'],
    ['検索結果ゼロ', () => Promise.resolve({ ok: true, json: async () => [] }), '店舗が見つかりませんでした'],
  ])('%sでは登録せずエラーを表示する', async (scenario, response, message) => {
    const user = userEvent.setup()
    const nextSearchAt = Date.now() + (scenario === '通信失敗' ? 5000 : 10000)
    vi.spyOn(Date, 'now').mockReturnValue(nextSearchAt)
    vi.stubGlobal('fetch', vi.fn(response))
    render(<App />)
    await user.click(screen.getByRole('button', { name: '店舗を追加' }))
    await user.type(screen.getByLabelText(/店舗名/), '未登録店舗')
    await user.type(screen.getByLabelText(/更新者/), '渡邉')
    await user.click(screen.getByRole('button', { name: '検索', exact: true }))
    expect(await screen.findByRole('alert')).toHaveTextContent(message)
    expect(screen.getByRole('dialog')).toBeVisible()
    expect(document.querySelectorAll('.store-marker')).toHaveLength(3)
    expect(localStorage.getItem(STORAGE_KEY)).toBeNull()
  })
  it('＋1は店舗名と座標を引き継ぎ、検索なしで追加して個別に削除できる', async () => {
    const user = userEvent.setup()
    const fetchMock = vi.fn().mockRejectedValue(new Error('offline'))
    vi.stubGlobal('fetch', fetchMock)
    const { unmount } = render(<App />)
    await user.click(screen.getByRole('button', { name: '銀座ライオン 七丁目店をもう一度登録' }))
    expect(screen.getByRole('dialog', { name: '訪問を登録' })).toBeVisible()
    expect(screen.getByLabelText(/店舗名/)).toHaveValue('銀座ライオン 七丁目店')
    expect(screen.getByLabelText(/店舗名/)).toHaveAttribute('readonly')
    expect(screen.getByLabelText(/更新者/)).toHaveValue('')
    expect(screen.queryByRole('button', { name: '検索', exact: true })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: '登録', exact: true })).toBeEnabled()
    expect(screen.queryByRole('radio')).not.toBeInTheDocument()
    expect(fetchMock).not.toHaveBeenCalled()
    await user.clear(screen.getByLabelText(/最終更新日/))
    await user.type(screen.getByLabelText(/最終更新日/), '2026-10-12')
    await user.type(screen.getByLabelText(/更新者/), '再訪者')
    await user.click(screen.getByRole('button', { name: '登録', exact: true }))
    expect(fetchMock).not.toHaveBeenCalled()
    const records = loadStores().stores.filter((store) => store.storeName === '銀座ライオン 七丁目店')
    expect(records).toHaveLength(2)
    expect(new Set(records.map((store) => store.registrationNo)).size).toBe(2)
    expect(records.some((store) => store.registrationNo === 'sample-1')).toBe(true)
    expect(records[1]).toMatchObject({ latitude: records[0].latitude, longitude: records[0].longitude })
    expect(screen.getByText('4 件')).toBeInTheDocument()
    expect(document.querySelectorAll('.store-marker')).toHaveLength(4)
    expect(within(screen.getByRole('table')).getAllByRole('cell', { name: '2 回' })).toHaveLength(2)
    unmount()
    render(<App />)
    expect(within(screen.getByRole('table')).getAllByRole('cell', { name: '2 回' })).toHaveLength(2)
    const originalRow = within(screen.getByRole('table')).getAllByRole('row')
      .find((row) => row.textContent.includes('銀座ライオン 七丁目店') && row.textContent.includes('2026/10/10'))
    await user.click(within(originalRow).getByRole('button', { name: '銀座ライオン 七丁目店を削除' }))
    await user.click(screen.getByRole('button', { name: '削除', exact: true }))
    const remaining = loadStores().stores.filter((store) => store.storeName === '銀座ライオン 七丁目店')
    expect(remaining).toHaveLength(1)
    expect(remaining[0]).toMatchObject({ updatedDate: '2026-10-12', updatedBy: '再訪者' })
    expect(document.querySelectorAll('.store-marker')).toHaveLength(3)
    expect(within(screen.getByRole('table')).queryByRole('cell', { name: '2 回' })).not.toBeInTheDocument()
    expect(within(screen.getByRole('table')).getAllByRole('cell', { name: '1 回' })).toHaveLength(3)
  })
  it('＋1でも必須入力を確認し、キャンセル時は訪問を増やさない', async () => {
    const user = userEvent.setup()
    const fetchMock = vi.fn()
    vi.stubGlobal('fetch', fetchMock)
    render(<App />)
    await user.click(screen.getByRole('button', { name: '銀座ライオン 七丁目店をもう一度登録' }))
    await user.click(screen.getByRole('button', { name: '登録', exact: true }))
    expect(screen.getByRole('dialog')).toBeVisible()
    expect(localStorage.getItem(STORAGE_KEY)).toBeNull()
    await user.click(screen.getByRole('button', { name: 'キャンセル', exact: true }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(fetchMock).not.toHaveBeenCalled()
    expect(within(screen.getByRole('table')).getAllByRole('cell', { name: '1 回' })).toHaveLength(3)
  })
  it('訪問数は同じ店舗名だけを集計し、各登録レコードを保持する', () => {
    const sample = loadStores().stores
    saveStores([...sample, { ...sample[0], registrationNo: 'repeat-1', updatedBy: '別の更新者' },
      { ...sample[0], registrationNo: 'repeat-2', updatedDate: '2026-10-12' }])
    render(<App />)
    const rows = within(screen.getByRole('table')).getAllByRole('row')
    const sameStoreRows = rows.filter((row) => row.textContent.includes(sample[0].storeName))
    expect(sameStoreRows).toHaveLength(3)
    for (const row of sameStoreRows) {
      expect(within(row).getByRole('cell', { name: '3 回' })).toBeInTheDocument()
    }
    expect(within(screen.getByRole('table')).getAllByRole('cell', { name: '1 回' })).toHaveLength(2)
    expect(loadStores().stores).toHaveLength(5)
    expect(loadStores().stores[0]).not.toHaveProperty('visitCount')
  })
  it.each(['id', 'registrationNo'])('旧%s形式の日付・名前を移行し、次回保存時に新形式で保存する', (key) => {
    const legacy = loadStores().stores.map(({ registrationNo, updatedDate, updatedBy, ...record }) => ({
      ...record, [key]: registrationNo, visitedDate: updatedDate, registeredBy: updatedBy,
    }))
    localStorage.setItem(STORAGE_KEY, JSON.stringify(legacy))
    const migrated = loadStores()
    expect(migrated.error).toBe('')
    expect(migrated.stores[0].registrationNo).toBe('sample-1')
    expect(migrated.stores[0]).not.toHaveProperty('id')
    expect(migrated.stores[0]).toMatchObject({ updatedDate: '2026-10-10', updatedBy: '渡邉' })
    expect(migrated.stores[0]).not.toHaveProperty('visitedDate')
    expect(migrated.stores[0]).not.toHaveProperty('registeredBy')
    saveStores(migrated.stores)
    expect(JSON.parse(localStorage.getItem(STORAGE_KEY))[0]).toHaveProperty('registrationNo', 'sample-1')
    expect(JSON.parse(localStorage.getItem(STORAGE_KEY))[0]).not.toHaveProperty('id')
    expect(JSON.parse(localStorage.getItem(STORAGE_KEY))[0]).not.toHaveProperty('visitedDate')
    expect(JSON.parse(localStorage.getItem(STORAGE_KEY))[0]).not.toHaveProperty('registeredBy')
    render(<App />)
    expect(document.querySelectorAll('.store-marker')).toHaveLength(3)
  })
  it('新旧の日付・名前がある場合は新項目を優先する', () => {
    const record = { ...loadStores().stores[0], visitedDate: '2020-01-01', registeredBy: '旧登録者' }
    saveStores([record])
    expect(loadStores().stores[0]).toMatchObject({ updatedDate: '2026-10-10', updatedBy: '渡邉' })
    expect(loadStores().stores[0]).not.toHaveProperty('visitedDate')
    expect(loadStores().stores[0]).not.toHaveProperty('registeredBy')
  })
  it('登録Noが重複した保存データを拒否する', () => {
    const records = loadStores().stores
    localStorage.setItem(STORAGE_KEY, JSON.stringify([records[0], records[0]]))
    expect(loadStores().error).not.toBe('')
  })
  it('保存失敗時は削除せずエラーを表示する', async () => {
    const user = userEvent.setup()
    render(<App />)
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('quota') })
    await user.click(screen.getByRole('button', { name: '銀座ライオン 七丁目店を削除' }))
    await user.click(screen.getByRole('button', { name: '削除', exact: true }))
    expect(screen.getByRole('alert')).toHaveTextContent('保存できませんでした')
    expect(document.querySelectorAll('.store-marker')).toHaveLength(3)
  })
  it('空の保存データではサンプルを復活させない', () => {
    localStorage.setItem(STORAGE_KEY, '[]')
    render(<App />)
    expect(screen.getByText('登録された店舗はありません')).toBeVisible()
    expect(document.querySelectorAll('.store-marker')).toHaveLength(0)
  })
  it('不正な保存データで画面がクラッシュしない', () => {
    localStorage.setItem(STORAGE_KEY, '{broken')
    render(<App />)
    expect(screen.getByRole('alert')).toHaveTextContent('保存データを読み込めませんでした')
  })
  it('表と地図の店舗名が同じGoogle検索を新しいタブで開くリンクになる', async () => {
    const user = userEvent.setup()
    render(<App />)
    const tableLink = screen.getByRole('link', { name: '銀座ライオン 七丁目店', exact: true })
    const searchUrl = new URL(tableLink.href)
    expect(searchUrl.origin).toBe('https://www.google.com')
    expect(searchUrl.pathname).toBe('/search')
    expect(searchUrl.searchParams.get('q')).toBe('銀座ライオン 七丁目店')
    expect(tableLink).toHaveAttribute('target', '_blank')
    expect(tableLink).toHaveAttribute('rel', 'noopener noreferrer')
    await user.click(screen.getByTitle('銀座ライオン 七丁目店'))
    await waitFor(() => expect(document.querySelector('.leaflet-popup-content')).toHaveTextContent('銀座ライオン 七丁目店'))
    const mapLink = within(document.querySelector('.leaflet-popup-content')).getByRole('link', { name: '銀座ライオン 七丁目店' })
    expect(mapLink).toHaveAttribute('href', tableLink.href)
    expect(mapLink).toHaveAttribute('target', '_blank')
    expect(mapLink).toHaveAttribute('rel', 'noopener noreferrer')
    expect(document.querySelector('.leaflet-popup-content')).toHaveTextContent('2026/10/10 · 渡邉')
  })
  it('Google検索リンクは店舗名の記号を安全にエンコードする', () => {
    const record = { ...loadStores().stores[0], storeName: '魚 & 酒 #1 + 新宿' }
    saveStores([record])
    render(<App />)
    const link = screen.getByRole('link', { name: record.storeName, exact: true })
    const url = new URL(link.href)
    expect(url.searchParams.get('q')).toBe(record.storeName)
    expect([...url.searchParams.keys()]).toEqual(['q'])
    expect(url.hash).toBe('')
  })
})